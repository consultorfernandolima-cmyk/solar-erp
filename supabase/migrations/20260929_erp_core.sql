create or replace function app_private.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at=now(); return new; end; $$;
do $$
declare t text;
begin
 foreach t in array array['organizacoes','empresas','perfis','parceiros','produtos_servicos','configuracoes_sistema'] loop
  execute format('drop trigger if exists %I on public.%I','trg_'||t||'_updated_at',t);
  execute format('create trigger %I before update on public.%I for each row execute function app_private.set_updated_at()','trg_'||t||'_updated_at',t);
 end loop;
end $$;
