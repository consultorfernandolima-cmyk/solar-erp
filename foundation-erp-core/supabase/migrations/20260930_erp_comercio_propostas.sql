  and exists (
    select 1 from public.parceiros c
    join public.parceiro_papeis pp on pp.parceiro_id = c.id and pp.papel = 'CLIENTE'
    where c.id = propostas.cliente_id and c.organizacao_id = propostas.organizacao_id and c.ativo
  )
);

