-- Comércio / Propostas
-- Persistência, permissões e RLS por organização + empresa.
-- Inclui composição de itens com validação do produto dentro da mesma organização.
-- Esta migração é idempotente para alinhar o repositório ao banco já provisionado.

create table if not exists public.propostas (
  id uuid primary key default gen_random_uuid(),
  organizacao_id uuid not null references public.organizacoes(id) on delete cascade,
  empresa_id uuid not null references public.empresas(id) on delete restrict,
  numero bigint generated by default as identity,
  cliente_id uuid not null references public.parceiros(id) on delete restrict,
  data_emissao date not null default current_date,
  validade date,
  status text not null default 'EM_ELABORACAO' check (status in ('EM_ELABORACAO','ENVIADA','NEGOCIACAO','APROVADA','RECUSADA','CANCELADA')),
  observacoes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint propostas_org_numero_uidx unique (organizacao_id, numero),
  constraint propostas_validade_ck check (validade is null or validade >= data_emissao)
);

create table if not exists public.proposta_itens (
  id uuid primary key default gen_random_uuid(),
  proposta_id uuid not null references public.propostas(id) on delete cascade,
  produto_id uuid not null references public.produtos_servicos(id) on delete restrict,
  quantidade numeric(14,3) not null check (quantidade > 0),
  valor_unitario numeric(14,2) not null check (valor_unitario >= 0),
  desconto numeric(14,2) not null default 0 check (desconto >= 0 and desconto <= quantidade * valor_unitario),
  observacoes text,
  created_at timestamptz not null default now()
);

create index if not exists propostas_empresa_idx on public.propostas(empresa_id);
create index if not exists propostas_cliente_idx on public.propostas(cliente_id);
create index if not exists propostas_status_idx on public.propostas(status);
create index if not exists proposta_itens_proposta_idx on public.proposta_itens(proposta_id);
create index if not exists proposta_itens_produto_idx on public.proposta_itens(produto_id);

