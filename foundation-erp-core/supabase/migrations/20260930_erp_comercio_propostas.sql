create policy propostas_select on public.propostas for select using (
  app_private.has_permission('comercio.propostas.visualizar')
  and exists (
    select 1 from public.empresas e
    where e.id = propostas.empresa_id and e.organizacao_id = propostas.organizacao_id and e.ativo
      and (
        exists (select 1 from public.perfis p where p.id = (select auth.uid()) and p.is_admin and p.organizacao_id = propostas.organizacao_id)
        or exists (select 1 from public.usuario_empresas ue where ue.usuario_id = (select auth.uid()) and ue.empresa_id = propostas.empresa_id)
      )
  )
);

create policy propostas_insert on public.propostas for insert with check (
  app_private.has_permission('comercio.propostas.criar')
  and exists (
    select 1 from public.empresas e
    where e.id = propostas.empresa_id and e.organizacao_id = propostas.organizacao_id and e.ativo
      and (
        exists (select 1 from public.perfis p where p.id = (select auth.uid()) and p.is_admin and p.organizacao_id = propostas.organizacao_id)
